#!/usr/bin/env node
// Builds the loadable extension into extension/dist/. Three steps and no bundler:
//   1. lift Playwright's injected script out of the installed playwright-core — the naming code;
//   2. compile extension/src with tsc;
//   3. copy extension/static.
// The lifted script is generated on every build and never committed: the extension and replay are
// the same bytes whenever both come from the same node_modules.
import { execFileSync } from "node:child_process";
import { copyFileSync, cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "extension", "dist");
const require = createRequire(import.meta.url);

const fail = (message) => {
  console.error(`build-extension: ${message}`);
  process.exit(1);
};

// --- 1. the naming code -------------------------------------------------------------------------
const corePackage = dirname(require.resolve("playwright-core/package.json"));
const { version } = require("playwright-core/package.json");
const core = readFileSync(require.resolve("playwright-core/lib/coreBundle"), "utf8");

const MARKER = "// packages/playwright-core/src/generated/injectedScriptSource.ts";
const at = core.indexOf(MARKER);
if (at === -1) fail(`playwright-core@${version} no longer has the marker "${MARKER}"; update this script.`);
// The first `<name> = '<string literal>';` after the marker is the injected script's source.
const literal = /^\s*\w+ = ('(?:[^'\\\n]|\\.)*');\s*$/m.exec(core.slice(at));
if (!literal) fail(`playwright-core@${version}: no string literal follows the marker; update this script.`);
// It is a single-quoted string literal from our own dependency and nothing else (the regex says so);
// evaluating it only un-escapes it.
const source = new Function(`return ${literal[1]};`)();
for (const needle of ["InjectedScript", "getElementAccessibleNameText", "getAriaRole", "isElementVisible", "createRoleEngine"]) {
  if (!source.includes(needle)) fail(`playwright-core@${version}: the injected script has no "${needle}"; update this script.`);
}

// Exactly how Playwright instantiates it (coreBundle.js, FrameExecutionContext.injectedScript),
// with the options a plain Chromium page gets. No custom engines, so nothing is eval'd.
const OPTIONS = {
  isUnderTest: false, sdkLanguage: "javascript", testIdAttributeName: "data-testid",
  stableRafCount: 1, browserName: "chromium", customEngines: [],
};
const naming = `playwright-core@${version}`;
const vendored = `// Playwright's injected script, lifted unmodified from ${naming} (Apache-2.0; see
// LICENSE.playwright and NOTICE.playwright beside this file). Generated by scripts/build-extension.mjs.
// This is the code replay resolves with. The extension computes no accessible name of its own.
globalThis.__vibetakeNaming = ${JSON.stringify(naming)};
globalThis.__vibetakeInjected = (() => {
const module = {};
${source}
return new (module.exports.InjectedScript())(globalThis, ${JSON.stringify(OPTIONS)});
})();
`;

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, "vendor"), { recursive: true });
writeFileSync(join(out, "vendor", "playwright-injected.js"), vendored);
copyFileSync(join(corePackage, "LICENSE"), join(out, "vendor", "LICENSE.playwright"));
copyFileSync(join(corePackage, "NOTICE"), join(out, "vendor", "NOTICE.playwright"));
// The zip library, same package on both sides of the hand-off (import uses it in Node).
const fflatePackage = dirname(require.resolve("fflate/package.json"));
copyFileSync(join(fflatePackage, "umd", "index.js"), join(out, "vendor", "fflate.js"));
copyFileSync(join(fflatePackage, "LICENSE"), join(out, "vendor", "LICENSE.fflate"));

// --- 2. our code ---------------------------------------------------------------------------------
execFileSync(process.execPath, [require.resolve("typescript/bin/tsc"), "-p", join(root, "extension")], { stdio: "inherit" });

// --- 3. static files -----------------------------------------------------------------------------
cpSync(join(root, "extension", "static"), out, { recursive: true });

console.log(`built extension/dist (naming: ${naming}; fflate ${require("fflate/package.json").version})`);
